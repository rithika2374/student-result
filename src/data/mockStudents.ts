function makeSubject(
  code: string,
  name: string,
  credits: number,
  maxTheory: number,
  maxInternal: number,
  theoryScore: number,
  internalScore: number
) {
  const { grade, gradePoint, status } = calculateSubjectGrade(theoryScore, internalScore, maxTheory, maxInternal);
  return {
    code,
    name,
    credits,
    maxTheory,
    maxInternal,
    theoryScore,
    internalScore,
    grade,
    gradePoint,
    status,
  };
}

